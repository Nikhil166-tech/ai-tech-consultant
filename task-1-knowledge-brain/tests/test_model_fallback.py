@pytest.mark.asyncio
async def test_cross_provider_fallback(mock_db):
    """When Google Gemini models fail, system seamlessly falls back to Anthropic Claude."""
    rag = HybridRAGEngine(db=mock_db)
    providers_hit = []

    def mock_post_cross_provider(url, **kwargs):
        url_str = str(url)
        mock_resp = MagicMock()
        if "generativelanguage.googleapis.com" in url_str:
            providers_hit.append("google")
            mock_resp.status_code = 503
            mock_resp.text = "High demand spike"
            return mock_resp
        elif "api.anthropic.com" in url_str:
            providers_hit.append("anthropic")
            mock_resp.status_code = 200
            mock_resp.json.return_value = {
                "content": [{"type": "text", "text": "Answer synthesized by Claude Sonnet"}],
                "usage": {"input_tokens": 15, "output_tokens": 10}
            }
            return mock_resp
        mock_resp.status_code = 500
        return mock_resp

    with patch("httpx.AsyncClient.post", new_callable=AsyncMock, side_effect=mock_post_cross_provider):
        with patch.object(rag, "gemini_api_key", "mock_gemini_key"):
            with patch.object(rag, "anthropic_api_key", "sk-ant-mock-key"):
                req = AskRequest(question="Where do I configure Stripe keys?")
                resp = await rag.ask(req)

                assert "google" in providers_hit
                assert "anthropic" in providers_hit
                assert "Claude Sonnet" in resp.answer
                assert resp.telemetry["provider"] == "anthropic"


