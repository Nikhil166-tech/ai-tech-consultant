def test_preview_models_require_explicit_opt_in():
    """Preview models must be excluded from candidate lists unless ALLOW_PREVIEW_MODELS=true."""
    engine_default = ModelFallbackEngine(role="KB_ANSWER")
    candidates_default = [m for _, m in engine_default.get_model_candidates()]
    assert not any("-preview" in m for m in candidates_default[1:]), "Preview models should not appear in default fallback cascade"

    with patch.dict(os.environ, {"ALLOW_PREVIEW_MODELS": "true"}):
        engine_preview = ModelFallbackEngine(role="KB_ANSWER")
        candidates_preview = [m for _, m in engine_preview.get_model_candidates()]
        assert any("-preview" in m for m in candidates_preview), "Preview models should be included when opted in"


@pytest.mark.asyncio
async def test_fallback_to_next_latest_gemini_model_when_primary_fails(mock_db):
    """
    When primary Gemini model returns 404 (model not found),
    the system must automatically fall back to the next latest Gemini model and succeed.
    """
    rag = HybridRAGEngine(db=mock_db)
    attempted_models = []

    def mock_post_side_effect(url, **kwargs):
        import re
        match = re.search(r"/models/([^:]+):generateContent", str(url))
        model = match.group(1) if match else "unknown"
        attempted_models.append(model)

        mock_resp = MagicMock()
        if len(attempted_models) == 1:
            mock_resp.status_code = 404
            mock_resp.text = '{"error": {"code": 404, "message": "Model not found"}}'
            return mock_resp
        else:
            mock_resp.status_code = 200
            mock_resp.json.return_value = {
                "candidates": [
                    {
                        "content": {
                            "parts": [
                                {"text": f"Answer generated by fallback model {model}: Navigate to Finance -> Payment Settings."}
                            ]
                        }
                    }
                ],
                "usageMetadata": {"totalTokenCount": 42}
            }
            return mock_resp

    with patch("httpx.AsyncClient.post", new_callable=AsyncMock, side_effect=mock_post_side_effect):
        with patch.object(rag, "gemini_api_key", "mock_gemini_key"):
            req = AskRequest(question="Where do I configure Stripe keys?")
            resp = await rag.ask(req)

            assert len(attempted_models) >= 2
            assert resp.is_known is True
            assert "Finance -> Payment Settings" in resp.answer
            assert len(resp.citations) > 0
            assert resp.telemetry is not None
            assert resp.telemetry["fallback_occurred"] is True


@pytest.mark.asyncio
async def test_fast_abort_on_invalid_credentials(mock_db):
    """Invalid credentials (HTTP 400 API_KEY_INVALID) must abort the provider loop without retrying other models."""
    rag = HybridRAGEngine(db=mock_db)
    attempts = []

    def mock_post_invalid_key(url, **kwargs):
        attempts.append(str(url))
        mock_resp = MagicMock()
        mock_resp.status_code = 400
        mock_resp.text = '{"error": {"code": 400, "message": "API key not valid. Please pass a valid API key."}}'
        return mock_resp

    with patch("httpx.AsyncClient.post", new_callable=AsyncMock, side_effect=mock_post_invalid_key):
        with patch.object(rag, "gemini_api_key", "invalid_gemini_key"):
            with patch.object(rag, "anthropic_api_key", None):
                req = AskRequest(question="Where do I configure Stripe keys?")
                resp = await rag.ask(req)

                # Should only make 1 attempt before fast-aborting Google models
                assert len(attempts) == 1
                assert resp.is_known is True
                assert resp.telemetry["model_selected"] == "deterministic_fallback"


